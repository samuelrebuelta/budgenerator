/*
 * Renders the Tailwind 4 `@theme` block of the web from the tokens. Pure and dependency-free so
 * that `scripts/build-theme.mjs` (Node) and the Vitest sync test share the exact same output.
 */
import {
  breakpoints,
  colorGroups,
  deprecatedBlueAlias,
  display,
  fonts,
  radii,
  shadows,
} from './tokens.ts';
import type { ShadowToken } from './tokens.ts';

const REM = 16;

const num = (n: number) => String(Number(n.toFixed(4)));
const rem = (px: number) => (px >= 999 ? `${px}px` : `${num(px / REM)}rem`);
const px = (n: number) => (n === 0 ? '0' : `${num(n)}px`);

export function shadowToCss(s: ShadowToken): string {
  return `${px(s.x)} ${px(s.y)} ${px(s.blur)} rgb(${s.rgb.join(' ')} / ${num(s.alpha)})`;
}

const comment = (text: string) => `  /* ${text} */`;

export function renderTheme(): string {
  const out: string[] = [];
  const decl = (name: string, value: string) => out.push(`  --${name}: ${value};`);
  const blank = () => out.push('');

  decl('font-sans', `'${fonts.sans.web}', ${fonts.sans.fallback}`);
  decl('font-display', `'${fonts.display.web}', ${fonts.display.fallback}`);

  colorGroups.forEach((group, i) => {
    blank();
    out.push(comment(group.comment));
    for (const [name, value] of Object.entries(group.values)) decl(`color-${name}`, value);
    if (i === 0) {
      blank();
      out.push(`  /*\n   * ${deprecatedBlueAlias.comment}\n   */`);
      for (const step of deprecatedBlueAlias.steps) {
        decl(`color-blue-${step}`, `var(--color-${deprecatedBlueAlias.of}-${step})`);
      }
    }
  });

  blank();
  out.push(comment('Radii: controls, cards, sheets and pills.'));
  for (const [name, value] of Object.entries(radii)) decl(`radius-${name}`, rem(value));

  blank();
  out.push(comment('Elevation.'));
  for (const [name, value] of Object.entries(shadows)) decl(`shadow-${name}`, shadowToCss(value));

  blank();
  out.push(comment('Shell breakpoint: side navigation from 801 px (`shell:` / `max-shell:`).'));
  decl('breakpoint-shell', rem(breakpoints.shell));

  blank();
  out.push(comment("Page titles. Body text uses Tailwind's xs–4xl scale; do not go below 12 px."));
  decl('text-display', `clamp(${rem(display.min)}, ${num(display.vw)}vw, ${rem(display.max)})`);
  decl('text-display--line-height', num(display.lineHeight));

  return `/*
 * GENERATED by scripts/build-theme.mjs from packages/ui-tokens. Do not edit by hand:
 * change the tokens in packages/ui-tokens/src/tokens.ts and run \`pnpm theme\`.
 *
 * Every value here generates a Tailwind utility (\`bg-surface\`, \`text-ink-muted\`,
 * \`rounded-card\`, \`shadow-popover\`, \`shell:\` …) and a CSS variable for component styles.
 * Use the semantic tokens in new code; the raw scales exist to build them.
 */
@theme {
${out.join('\n')}
}
`;
}
